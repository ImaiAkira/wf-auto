"""#119：三份 ``classify`` 去重成一份 —— 入库真机帧的「三份实现一致性」回归。

跑法::

    .venv\\Scripts\\python.exe tools\\test_classify_equiv.py

## 背景（票 #119 的实证，别再重新发现）

``classify``（把全屏 OCR 分成画面名）曾在**三个文件**里各写一份：
``battle_loop_core`` / ``abyss_impl`` / ``wuchong_impl``。#107 给
``battle_loop_core.is_battle_hud`` 加了「HUD 被 toast 遮挡时的多视觉特征兜底」，但另外两份
``classify`` 根本没调它 —— 同一帧上 ``is_battle_hud=True``，幻想判 ``battle``、另外两份判
``unknown``，真机幻想 912 秒死循环。**一个正确的修复被重复实现静默废掉**，比 bug 更危险。
去重后判据只剩一份，本文件负责证明「三个入口在同一帧上给出同一个语义状态」。

## 本文件钉什么

1. **共同词汇**（``SHARED`` 帧）：同一帧三份实现必须给**同一个语义状态**（允许前缀不同，
   比较语义名）。覆盖票面点名的七类：战斗可读 / 战斗被遮 / 结算 / 编队页 / 主城 / 列表页 / 未知。
2. **场景专有页**（``SCENE`` 帧）：终始之战列表只属于幻/渊（``zhongshi``）、领主战列表只属于
   五重（``wuchong_lord_list``）、模式页只属于五重（``wuchong_mode``）；其余场景必须是
   ``unknown``。★任何场景都不许返回别的场景的前缀★（跨场景状态名混用，见 #100 的教训）。
3. **遮挡帧的承重证据**：``wuchong_hud_occluded.png`` 上共享 ``is_battle_hud=True``、而
   「底部条带时间+分数」主判据**不成立** ⇒ 幻/渊必须靠 ``hud_fallback`` 命中、五重靠直接 HUD；
   三份都判 battle。这正是 #107/#118 的修复要在三个场景同时生效的回归。
4. **薄封装等价**：``abyss_impl.classify`` / ``wuchong_impl.classify`` 与
   ``core.classify(自己的配置, ...)`` 逐帧同值 —— 它们只允许是薄封装（AST 层由
   ``tools/contract_hooks/hooks_119.py`` ② 把守）。
5. **读数不是手写的**（best-effort）：真跑一次 MaaFramework OCR，把**状态判定**与内嵌读数
   对账；缺 maa / OCR 模型时 SKIP（与 ``test_abyss_117`` 同一口径）。

## 数据来源

下面每帧的 ``items`` = ``tools/frames/<name>`` 的 **720 空间 OCR 逐条读数**（MAA ``OcrTask``
真跑一次后内嵌，帧文件随仓）。真 OCR 复核腿会重新求值，因此这不是「拿手写数据喂自己」。
"""

