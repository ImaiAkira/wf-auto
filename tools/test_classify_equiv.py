# 5. 真 OCR 复核（best-effort）：内嵌读数不是手写的
# ---------------------------------------------------------------------------
def _maa_ocr(frame: Path):
    """对随仓帧真跑一次 MAA OCR（720 空间）；缺 maa / 模型 / 帧 → None（SKIP）。"""
    if not frame.is_file():
        return None
    if not (_ASSETS / "model" / "ocr" / "det.onnx").is_file():
        return None
    try:
        import numpy as np
        from PIL import Image

        import live_harness as ca
    except Exception:  # noqa: BLE001
        return None
    try:
        pil = Image.open(frame).convert("RGB")
        if pil.size != (720, 1280):
            pil = pil.resize((720, 1280), Image.LANCZOS)
        img = np.ascontiguousarray(np.array(pil)[:, :, ::-1])
        return ca.ocr(img, _ASSETS)
    except Exception:  # noqa: BLE001
        return None


def test_real_ocr_cross_check() -> None:
    print("\n== 5. 真 OCR 复核：内嵌读数重新求值后结论不变（缺 maa/模型则 SKIP）==")
    for frame in FRAMES:
        real = _maa_ocr(ROOT / "tools" / "frames" / frame.name)
        if real is None:
            skip(f"真 OCR：{frame.name}", "缺 maa / OCR 模型 det.onnx / 帧")
            continue
        got = tuple(semantic(c([tuple(x) for x in real])[0]) for _l, c in IMPLS)
        check(f"真 OCR：{frame.name} 语义状态 == 内嵌读数", got == frame.want, f"实际 {got}")


