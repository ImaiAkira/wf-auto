def semantic(state: str) -> str:
    """状态名 -> 语义名（允许前缀不同，比较语义）。"""
    if state in core.BARE_STATES or state == "unknown":
        return state
    for prefix in _PREFIXES:
        if state.startswith(prefix):
            return _SEMANTIC_ALIASES.get(state[len(prefix):], state[len(prefix):])
    raise AssertionError(f"不认识的状态名 {state!r}（既不裸名也不带已知前缀）")


