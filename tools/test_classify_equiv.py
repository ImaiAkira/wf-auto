def check(name: str, cond: bool, extra: str = "") -> None:
    print(f"  [{'PASS' if cond else 'FAIL'}] {name}" + (f"  {extra}" if extra else ""))
    if not cond:
        FAILS.append(name)


def skip(name: str, why: str) -> None:
    print(f"  [SKIP] {name}  ({why})")
    SKIPS.append(name)


def _states(frame: Frame) -> tuple:
    """这帧在三份实现下的原始状态三元组。"""
    items = [tuple(x) for x in frame.items]
    return tuple(classify(items)[0] for _label, classify in IMPLS)


def _semantics(frame: Frame) -> tuple:
    return tuple(semantic(s) for s in _states(frame))


# ---------------------------------------------------------------------------
# 1. 三份实现的一致性（共同词汇 + 场景专有页）
# ---------------------------------------------------------------------------
def test_equivalence() -> None:
    print("\n== 1. 同一帧：三份实现的语义状态 ==")
    labels = tuple(label for label, _c in IMPLS)
    for frame in FRAMES:
        states = _states(frame)
        got = tuple(semantic(s) for s in states)
        print(f"  {frame.name}: {labels} -> {got}  (raw={states})")
        check(f"{frame.name}: 语义状态 == 期望 {frame.want}", got == frame.want, f"实际 {got}")

        # ★跨场景状态名混用红线★：每个实现返回的状态前缀必须是**它自己的**。
        for label, state in zip(labels, states):
            if state == "unknown" or state in core.BARE_STATES:
                continue
            prefix = state.split("_", 1)[0]
            check(
                f"{frame.name}: {label} 的状态名 {state!r} 用**自己的**前缀",
                prefix == label,
                f"prefix={prefix!r} expected={label!r}",
            )

        if frame.kind == SHARED:
            check(
                f"{frame.name}: 三份实现互相一致（共同词汇）",
                got[0] == got[1] == got[2] == frame.cls,
                f"{got}",
            )
        else:
            check(f"{frame.name}: 场景专有页（类别 {frame.cls}）", frame.kind == SCENE)


