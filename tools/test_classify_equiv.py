# 2. 覆盖：票面点名的七类一帧都不许少（防止用例退化成「全 unknown 也相等」）
# ---------------------------------------------------------------------------
def test_coverage() -> None:
    print("\n== 2. 覆盖：战斗可读 / 战斗被遮 / 结算 / 编队页 / 主城 / 列表页 / 未知 ==")
    covered = {f.cls for f in FRAMES} | {t for f in FRAMES for t in f.tags}
    required = {
        "battle",            # 战斗可读
        "battle_occluded",   # 战斗被遮（#107/#118 的承重帧）
        "settle",            # 结算
        "team",              # 编队页
        "main_city",         # 主城
        "list_zhongshi",     # 列表页（终始之战，幻/渊）
        "list_lord",         # 列表页（领主战，五重；#56/#103 的现场）
        "unknown",           # 未知
    }
    missing = sorted(required - covered)
    check("票面七类都有真机帧覆盖", missing == [], f"缺 {missing}")
    check("共享词汇帧 ≥ 12（不是只测了场景专有页）",
          sum(1 for f in FRAMES if f.kind == SHARED) >= 12,
          f"{sum(1 for f in FRAMES if f.kind == SHARED)} 帧")
    # 每一类「共享」都必须**三份实现一致**地出现（不是只有一份认出来）。
    for cls in ("battle", "settle", "team", "main_city", "unknown"):
        same = [
            f for f in FRAMES
            if f.cls == cls and f.kind == SHARED and f.want == (cls, cls, cls)
        ]
        check(f"共同词汇 {cls!r} 至少一帧三份一致", bool(same), f"{len(same)} 帧")


